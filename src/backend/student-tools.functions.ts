/* ============================================================================
 * Student-facing AI tools hosted inside "Meu Diário":
 *   - Resumo + Glossário
 *   - Mapa Conceitual
 *   - Guia de Estudo
 * Each tool consumes published materials of the discipline (and optionally
 * apostilas generated by the teacher and the discipline's ementa). Outputs are
 * persisted as `student_diary_entries` so they are automatically saved in the
 * student's diary.
 * ========================================================================== */

async function assertEnrolled(disciplineId: string, userId: string) {
  const { data: disc } = await supabaseAdmin
    .from("disciplines")
    .select("id, teacher_id")
    .eq("id", disciplineId)
    .maybeSingle();
  if (!disc) throw new Error("Disciplina não encontrada");
  if (disc.teacher_id === userId) return; // teacher previewing is fine
  const { data: enr } = await supabaseAdmin
    .from("discipline_students")
    .select("id")
    .eq("discipline_id", disciplineId)
    .eq("student_id", userId)
    .maybeSingle();
  if (!enr) throw new Error("Sem permissão");
}

async function loadDisciplineContext(disciplineId: string) {
  const { data: disc } = await supabaseAdmin
    .from("disciplines")
    .select("id, name, group_name, teacher_id, institution_id, syllabus_text")
    .eq("id", disciplineId)
    .maybeSingle();
  if (!disc) throw new Error("Disciplina não encontrada");
  const [{ data: teacher }, instRes] = await Promise.all([
    supabaseAdmin.from("profiles").select("name").eq("id", disc.teacher_id).maybeSingle(),
    disc.institution_id
      ? supabaseAdmin.from("institutions").select("name").eq("id", disc.institution_id).maybeSingle()
      : Promise.resolve({ data: null as { name: string } | null }),
  ]);
  const teacherName =
    teacher?.name && !/^estudaj[áa]\s*pro$/i.test(teacher.name) ? teacher.name : "Não informado";
  const { resolveBrandingLogoUrl } = await import("./branding.server");
  const logoUrl = await resolveBrandingLogoUrl(disc.teacher_id).catch(() => null);
  return {
    discipline: disc,
    institution: instRes.data?.name ?? "Não informada",
    course: disc.group_name ?? "Não informado",
    teacherName,
    logoUrl,
  };
}

/**
 * Standardized document header matching the teacher's documents: institution
 * logo on the left, then Disciplina / Curso / Professor(a). An optional
 * identification line (e.g. "**Guia de Estudo:** <tema>") is appended right
 * after the professor — so the document name appears exactly once, inside the
 * header, just like the other documents.
 */
function buildHeader(
  ctx: { course: string; discipline: { name: string }; teacherName: string; logoUrl?: string | null },
  doc?: { label: string; value: string },
): string {
  const lines: string[] = [];
  if (ctx.logoUrl) lines.push(`![Logo](${ctx.logoUrl})`, "");
  lines.push(`**Disciplina:** ${ctx.discipline.name}`);
  lines.push(`**Curso:** ${ctx.course}`);
  lines.push(`**Professor(a):** ${ctx.teacherName}`);
  if (doc?.label) lines.push(`**${doc.label}:** ${doc.value}`);
  lines.push("", "---", "");
  return lines.join("\n");
}

type SourceKind = "material" | "apostila" | "ementa";
type SourceItem = {
  id: string;
  kind: SourceKind;
  title: string;
  module?: string | null;
  created_at?: string | null;
};

export const listStudentSources = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .validator((input) =>
    z
      .object({
        discipline_id: z.string().uuid(),
        include_apostila: z.boolean().default(true),
        include_ementa: z.boolean().default(false),
      })
      .parse(input),
  )
  .handler(async ({ data, context }) => {
    if (!context.userId) throw new Error("Não autenticado");
    await assertEnrolled(data.discipline_id, context.userId);
    const items: SourceItem[] = [];

    if (data.include_apostila) {
      const { data: apos } = await (
        supabaseAdmin.from("ai_generations" as never) as unknown as {
          select: (s: string) => {
            eq: (k: string, v: string) => {
              eq: (k: string, v: string) => {
                order: (k: string, o: { ascending: boolean }) => Promise<{ data: Array<{ id: string; title: string; created_at: string }> | null }>;
              };
            };
          };
        }
      )
        .select("id, title, created_at")
        .eq("discipline_id", data.discipline_id)
        .eq("tool", "apostila")
        .order("created_at", { ascending: true });
      for (const a of apos ?? [])
        items.push({ id: a.id, kind: "apostila", title: a.title, created_at: a.created_at });
    }

    const { data: modules } = await supabaseAdmin
      .from("material_modules")
      .select("id, name, position")
      .eq("discipline_id", data.discipline_id)
      .order("position", { ascending: true });
    const modMap = new Map<string, string>();
    for (const m of modules ?? []) modMap.set(m.id, m.name);

    const { data: mats } = await supabaseAdmin
      .from("materials")
      .select("id, title, module_id, status, created_at")
      .eq("discipline_id", data.discipline_id)
      .eq("status", "published")
      .order("created_at", { ascending: true });
    for (const m of mats ?? [])
      items.push({
        id: m.id,
        kind: "material",
        title: m.title,
        module: modMap.get(m.module_id) ?? null,
        created_at: m.created_at,
      });

    if (data.include_ementa) {
      const { data: disc } = await supabaseAdmin
        .from("disciplines")
        .select("syllabus_text, name")
        .eq("id", data.discipline_id)
        .maybeSingle();
      if (disc?.syllabus_text && String(disc.syllabus_text).trim().length > 0) {
        items.push({ id: "ementa", kind: "ementa", title: `Ementa — ${disc.name}` });
      }
    }

    // Ordena por Módulo/Aula em ordem crescente (Módulo 1, 2, 3...), considerando
    // o nome do módulo do material e o título do documento.
    items.sort((a, b) => {
      const titleA = (a.module ? `${a.module} ` : "") + (a.title || "");
      const titleB = (b.module ? `${b.module} ` : "") + (b.title || "");
      return titleA.localeCompare(titleB, undefined, { numeric: true, sensitivity: 'base' });
    });
    return { items };
  });

async function loadSourceContent(
  disciplineId: string,
  src: { id: string; kind: SourceKind },
): Promise<{ title: string; content: string }> {
  if (src.kind === "ementa") {
    const { data: disc } = await supabaseAdmin
      .from("disciplines")
      .select("syllabus_text, name")
      .eq("id", disciplineId)
      .maybeSingle();
    return { title: `Ementa — ${disc?.name ?? ""}`, content: String(disc?.syllabus_text ?? "") };
  }
  if (src.kind === "apostila") {
    const { data: row } = await (
      supabaseAdmin.from("ai_generations" as never) as unknown as {
        select: (s: string) => {
          eq: (k: string, v: string) => {
            maybeSingle: () => Promise<{ data: { title: string; result: unknown; discipline_id: string | null } | null }>;
          };
        };
      }
    )
      .select("title, result, discipline_id")
      .eq("id", src.id)
      .maybeSingle();
    if (!row || row.discipline_id !== disciplineId) throw new Error("Apostila não encontrada");
    const md = extractAIContent(row.result).replace(/\\n/g, "\n");
    return { title: row.title, content: md };
  }
  // material
  const { data: mat } = await supabaseAdmin
    .from("materials")
    .select("title, content, file_url, status, discipline_id")
    .eq("id", src.id)
    .maybeSingle();
  if (!mat || mat.discipline_id !== disciplineId || mat.status !== "published")
    throw new Error("Material não encontrado");
  let text = String(mat.content ?? "").trim();
  if (!text && mat.file_url) {
    try {
      text = await extractTextFromFile(mat.file_url);
    } catch {
      text = "";
    }
  }
  if (!text) text = "(Conteúdo textual não disponível para este material.)";
  return { title: mat.title, content: text };
}

function truncate(s: string, max: number): string {
  return s.length > max ? s.slice(0, max) + "\n\n[...conteúdo truncado para o limite do prompt...]" : s;
}

async function saveDiaryEntry(opts: {
  studentId: string;
  disciplineId: string;
  title: string;
  content: string;
}): Promise<string> {
  const { data, error } = await supabaseAdmin
    .from("student_diary_entries")
    .insert({
      student_id: opts.studentId,
      discipline_id: opts.disciplineId,
      title: opts.title,
      content: opts.content,
    })
    .select("id")
    .single();
  if (error || !data) throw new Error(error?.message ?? "Erro ao salvar no diário");
  return data.id;
}

