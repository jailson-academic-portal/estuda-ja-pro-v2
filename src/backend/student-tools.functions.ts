function bufferToBase64(bytes: Uint8Array): string {
  let binary = "";
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk)
    binary += String.fromCharCode(...bytes.subarray(i, i + chunk));
  return btoa(binary);
}

export const exportDiaryEntryDOCX = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .validator((input) => z.object({ entry_id: z.string().uuid() }).parse(input))
  .handler(async ({ data, context }) => {
    if (!context.userId) throw new Error("Não autenticado");
    const { data: entry, error } = await supabaseAdmin
      .from("student_diary_entries")
      .select("id, student_id, title, content")
      .eq("id", data.entry_id)
      .maybeSingle();
    if (error) throw new Error(error.message);
    if (!entry || entry.student_id !== context.userId) throw new Error("Não encontrado");
    const { Document, Packer, Paragraph, TextRun, HeadingLevel, ImageRun } = await import("docx");
    const md = String(entry.content ?? "").replace(/\r\n/g, "\n");
    const children: InstanceType<typeof Paragraph>[] = [];
    const runs = (text: string) =>
      text
        .split(/(\*\*[^*]+\*\*)/g)
        .filter(Boolean)
        .map((p) =>
          p.startsWith("**") && p.endsWith("**")
            ? new TextRun({ text: p.slice(2, -2), bold: true })
            : new TextRun(p),
        );
    for (const raw of md.split("\n")) {
      const line = raw.trimEnd();
      if (!line.trim()) {
        children.push(new Paragraph({ text: "" }));
        continue;
      }
      if (line.trim() === "---") {
        children.push(new Paragraph({ text: "" }));
        continue;
      }
      const image = line.trim().match(/^!\[[^\]]*\]\(([^)]+)\)$/);
      if (image) {
        try {
          const res = await fetch(image[1]);
          if (res.ok) {
            const buf = new Uint8Array(await res.arrayBuffer());
            const isPng = buf[0] === 0x89 && buf[1] === 0x50;
            children.push(
              new Paragraph({
                children: [
                  new ImageRun({
                    type: isPng ? "png" : "jpg",
                    data: buf,
                    transformation: { width: 151, height: 76 },
                  }),
                ],
              }),
            );
          }
        } catch {
          /* skip logo on failure */
        }
        continue;
      }
      const h = line.match(/^(#{1,3})\s+(.+)$/);
      if (h) {
        children.push(
          new Paragraph({
            heading:
              h[1].length === 1
                ? HeadingLevel.HEADING_1
                : h[1].length === 2
                  ? HeadingLevel.HEADING_2
                  : HeadingLevel.HEADING_3,
            children: [new TextRun({ text: h[2].replace(/\*\*/g, ""), bold: true })],
          }),
        );
        continue;
      }
      const indent = line.match(/^(\s*)/)?.[1].length ?? 0;
      const bulleted = line.replace(/^(\s*)[-*+•]\s+/, "$1• ");
      const paragraph = new Paragraph({
        children: runs(bulleted),
        indent: indent > 0 ? { left: indent * 120 } : undefined,
      });
      children.push(paragraph);
    }
    const buf = await Packer.toBuffer(new Document({ sections: [{ children }] }));
    const bytes = new Uint8Array(buf);
    const safe = (entry.title ?? "").replace(/[^\w\s-]/g, "").trim() || "documento";
    return {
      filename: `${safe}.docx`,
      mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      base64: bufferToBase64(bytes),
    };
  });

